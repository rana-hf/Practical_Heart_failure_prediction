x_train = scaler.fit_transform(x_train)
x_test = scaler.transform(x_test)

"""# model 1"""

from sklearn.linear_model import LogisticRegression
# Feature selection
from sklearn.feature_selection import SelectKBest, chi2
from sklearn.preprocessing import MinMaxScaler

x_train_scaled_pos = MinMaxScaler().fit_transform(x_train)
x_test_scaled_pos = MinMaxScaler().fit_transform(x_test)
sel = SelectKBest(chi2, k=8)
x_train_selected = sel.fit_transform(x_train_scaled_pos, y_train)
x_test_selected = sel.transform (x_test_scaled_pos)
model = LogisticRegression(C=1, penalty= "l1", solver='liblinear',class_weight ='balanced',max_iter=1000)
model.fit(x_train_selected, y_train)

# Prediction
y_pred = model.predict(x_test_selected)

print('Training set score: {:.4f}'.format(
    model.score(x_train_selected, y_train)
))

print('Test set score: {:.4f}'.format(
    model.score(x_test_selected, y_test)
))

